const PALETTE = {
  '0': null, // пусто
  'e': '#d4a373', // кожа
  'd': '#8b5a2b', // тёмно-коричневый (волосы/пальто)
  'b': '#4a3b2b', // сапоги/штаны
  'w': '#ffffff', // белый
  'r': '#d94a4a', // красный (мундир)
  'g': '#888888', // серый (оружие)
  'p': '#9b59b6', // фиолетовый
  'k': '#111111'  // чёрный (глаза)
};

// Функция генерации текстуры из массива
function createPixelTexture(scene, key, matrix, pixelSize = 4) {
  const w = matrix[0].length * pixelSize;
  const h = matrix.length * pixelSize;
  
  const canvas = scene.textures.createCanvas(key, w, h);
  const ctx = canvas.getContext();

  for (let r = 0; r < matrix.length; r++) {
    for (let c = 0; c < matrix[r].length; c++) {
      const color = PALETTE[matrix[r][c]];
      if (color) {
        ctx.fillStyle = color;
        ctx.fillRect(c * pixelSize, r * pixelSize, pixelSize, pixelSize);
      }
    }
  }
  canvas.refresh();
}

